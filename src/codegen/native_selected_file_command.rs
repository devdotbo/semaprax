/// Emit the additive resource profile, preserving the exact v33 projection.
pub fn emit_hir_c_with_selected_file_resource_command(
    program: &crate::hir::ResolvedProgram,
) -> Result<String, crate::diagnostic::Diagnostic> {
    crate::hir::validate(program)?;
    crate::source_command::validate_resource_output_authority(program)?;
    crate::command_io_ops::validate_operation_profile(
        program,
        &program.entrypoint,
        crate::command_io_ops::CommandOperationProfile::SourceResourceV1,
    )?;
    if !cfg!(all(unix, target_pointer_width = "64")) {
        return Err(crate::diagnostic::Diagnostic::io(
            "SPX-B104",
            "source-command.selected-file.resource-output.v1 requires a native64 Unix host",
        ));
    }
    super::reject_native_rust_for_native(program)?;
    super::emit_hir_c_with_labels(
        program,
        &std::collections::HashMap::new(),
        super::NativeOutputProfile::SourceSelectedFileResourceCommand,
        None,
    )
}

pub(super) fn emit_resource_runtime(output: &mut impl COutput) {
    output.push_str(super::native_source_resource_command::OUTPUT_RUNTIME_C);
    // This closed profile changes only the private argv carrier's exact bound.
    // Neither the ordinary command runtime nor v33's generated bytes change.
    let mut arguments = String::new();
    super::native_command_io::emit_line_runtime(&mut arguments);
    output.push_str(&arguments.replace(
        "#define SPX_COMMAND_ARGUMENT_LIMIT_V1 UINT32_C(16)",
        "#define SPX_COMMAND_ARGUMENT_LIMIT_V1 UINT32_C(256)",
    ));
    output.push_str(include_str!(
        "native_selected_file_command/resource_table.c"
    ));
    let file_runtime = include_str!("native_selected_file_command/runtime.c");
    // The file provider has identical authority and bounds; only its output
    // helper inventory differs. The leading table is private static source.
    let (_, provider) = file_runtime
        .split_once("#if !defined(_WIN32)")
        .expect("selected file provider must retain its platform guard");
    output.push_str("#if !defined(_WIN32)");
    output.push_str(provider);
}

